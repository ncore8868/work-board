function 시트만들기() {
  var ss = ss_();
  var 만듦 = [], 있음 = [];

  만들목록.forEach(function (정의) {
    if (ss.getSheetByName(정의.이름)) { 있음.push(정의.이름); return; }

    var 탭 = ss.insertSheet(정의.이름);
    var 열수 = 정의.제목.length;

    탭.getRange(1, 1, 1, 열수).setValues([정의.제목])
      .setFontWeight('bold')
      .setBackground('#F1F3F4')
      .setVerticalAlignment('middle');
    탭.setFrozenRows(1);

    /* 전화번호 열은 글자로 고정한다.
       시트가 숫자로 읽으면 01027256026 의 앞자리 0 이 사라져
       PIN 이 전부 안 맞게 된다. */
    (정의.글자열 || []).forEach(function (c) {
      탭.getRange(2, c, 500, 1).setNumberFormat('@');
    });

    /* 요청 안에 담아둔 값이 있으면 버린다 (새 시트라 낡은 값이 남으면 안 된다) */
    try { delete _VALS[정의.이름]; delete _OBJ[정의.이름]; delete _HEAD[정의.이름]; } catch (e) {}

    /* 기본 줄 넣기 */
    var 줄들 = 기본줄[정의.이름];
    if (줄들 && 줄들.length) {
      var 값 = 줄들.map(function (o) {
        return 정의.제목.map(function (h) {
          return o[h] === undefined ? '' : o[h];
        });
      });
      탭.getRange(2, 1, 값.length, 열수).setValues(값);
    }

    만듦.push(정의.이름 + (줄들 ? ' (기본 ' + 줄들.length + '줄 포함)' : ''));
  });

  /* 담아둔 캐시를 전부 버린다. 다음 요청이 시트에서 새로 읽는다 */
  try { bumpAllSheets_(); } catch (e) {}
  try { bumpMeta_(); } catch (e) {}
  try { _VALS = {}; _HEAD = {}; _OBJ = {}; _META = null; } catch (e) {}

  var 결과 =
    '새로 만든 시트 ' + 만듦.length + '개\n' +
    (만듦.length ? '  ' + 만듦.join('\n  ') + '\n' : '') +
    '\n이미 있던 시트 ' + 있음.length + '개\n' +
    (있음.length ? '  ' + 있음.join(' · ') + '\n' : '') +
    '\n지금 스프레드시트의 전체 탭 ' + ss.getSheets().length + '개\n  ' +
    ss.getSheets().map(function (s) { return s.getName(); }).join(' · ') +
    '\n\n이어서 [점검_지금하기] 를 실행하세요.';

  Logger.log(결과);
  return 결과;
}


/* =============================================================
 *  확인용 — 무엇이 있고 무엇이 없는지만 봅니다. 아무것도 바꾸지 않습니다
 * ============================================================= */
function 시트확인() {
  var ss = ss_();
  var 있는것 = {};
  ss.getSheets().forEach(function (s) { 있는것[s.getName()] = s.getLastRow() - 1; });

  var 필요 = ['설정', '직원', '법인', '업무', '업무일지', '업무상세',
              '결재문서', '결재선', '결재내역', '문서상세', '양식항목', '문서양식',
              '정산내역', '첨부', '알림', '로그', '게시글', '댓글',
              '연동캐시', '서명', '읽음', '휴가', '업무유형'];

  var 줄 = ['스프레드시트  →  ' + ss.getName(), ''];
  var 없는것 = [];

  필요.forEach(function (n) {
    if (있는것[n] === undefined) { 줄.push('  ✕  ' + n); 없는것.push(n); }
    else 줄.push('  ○  ' + n + '   ' + 있는것[n] + '줄');
  });

  줄.push('');
  줄.push(없는것.length
    ? '★ 빠진 시트 ' + 없는것.length + '개 — [시트만들기] 를 실행하세요'
    : '필요한 시트가 전부 있습니다');

  var 결과 = 줄.join('\n');
  Logger.log(결과);
  return 결과;
}
